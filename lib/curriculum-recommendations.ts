/** Диапазоны цели по баллам — используются и на самом онбординге (кнопки
 * выбора), и в текстовой рекомендации по темпу на дашборде. */
export const TARGET_SCORE_RANGES = [
  { value: 65, label: "60–70" },
  { value: 75, label: "70–80" },
  { value: 85, label: "80–90" },
  { value: 95, label: "90–100" },
] as const;

/** Текстовая рекомендация по темпу занятий под указанную цель. */
export function targetScoreRecommendation(targetScore: number | undefined): string | null {
  if (!targetScore) return null;
  if (targetScore >= 90) {
    return "Цель 90+ баллов — понадобится и база, и сложные задачи (№13–19). Рекомендуем заниматься каждый день, не пропуская.";
  }
  if (targetScore >= 80) {
    return "Цель 80+ баллов — уверенное владение базой плюс часть сложных задач. 4–5 дней в неделю обычно достаточно.";
  }
  return "На вашу цель важнее всего база — задачи первой части ЕГЭ. Регулярность важнее интенсивности.";
}
