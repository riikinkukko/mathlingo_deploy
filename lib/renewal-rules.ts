/**
 * Правила автопродления тарифа репетитора. Отдельный модуль без импортов —
 * его берёт и lib/queries.ts, и lib/renewal.ts.
 *
 * Отклонённое списание (нет денег на карте, банк отказал) повторяем не каждый
 * день бесконечно: всего RENEWAL_MAX_ATTEMPTS попыток — в день окончания,
 * через день и ещё через два дня. Потом автопродление останавливается, карта
 * остаётся сохранённой, репетитор продлевает тариф сам.
 */
export const RENEWAL_MAX_ATTEMPTS = 3;

/** Текст уведомления после неудачной попытки №failures (1..RENEWAL_MAX_ATTEMPTS). */
export function renewalFailureMessage(failures: number): { title: string; body: string } {
  if (failures >= RENEWAL_MAX_ATTEMPTS) {
    return {
      title: "Автопродление тарифа остановлено",
      body: "Банк несколько раз отклонил списание, поэтому больше пробовать не будем. Продлите тариф вручную на странице «Тариф» — ученики и данные никуда не денутся.",
    };
  }
  const nextIn = failures === 1 ? "завтра" : "через 2 дня";
  return {
    title: "Не удалось продлить тариф",
    body: `Банк отклонил списание с сохранённой карты. Попробуем ещё раз ${nextIn}. Проверьте баланс карты или продлите тариф вручную на странице «Тариф».`,
  };
}
